static const size_t DTC_TABLE_LEN = sizeof(DTC_TABLE) / sizeof(DTC_TABLE[0]);

// Вернуть краткое описание по коду ("P0301"). Пусто, если нет в базе.
inline String dtcDescribe(const String& code) {
  char c[6]; char d[48];
  for (size_t i = 0; i < DTC_TABLE_LEN; i++) {
    strncpy_P(c, DTC_TABLE[i].code, sizeof(c));
    c[5] = 0;
    if (code == c) {
      strncpy_P(d, DTC_TABLE[i].desc, sizeof(d));
      d[47] = 0;
      return String(d);
    }
  }
  return "";
}
